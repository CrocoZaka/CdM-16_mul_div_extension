# ==================================================
# Тестовый набор для MDU
# Соглашения:
#   MUL: rA = Младшие 16 бит, rB = Старшие 16 бит
#   DIV: rA = Частное, rB = Остаток
# ==================================================
asect 0x00
dw start
dw 0
align 0x80

start:
# Базовая очистка регистров перед запуском тестов
ldi r0, 0
ldi r1, 0
ldi r2, 0
ldi r3, 0
ldi r4, 0
ldi r5, 0

# ==========================================
# 1. SMUL (Знаковое умножение)
# ==========================================
ldi r5, 0x11 # SMUL Тест: + на +
ldi r0, 12
ldi r1, 5
smul r0, r1
# Ожидается: r0=60(0x3c), r1=0, Flags: Z=0, N=0

ldi r5, 0x12 # SMUL Тест: - на -
ldi r0, -12
ldi r1, -5
smul r0, r1
# Ожидается: r0=60(0x3c), r1=0, Flags: Z=0, N=0

ldi r5, 0x13 # SMUL Тест: + на -
ldi r0, 12
ldi r1, -5
smul r0, r1
# Ожидается: r0=-60(0xffc4), r1=-1 (0xFFFF), Flags: N=1

ldi r5, 0x14 # SMUL Тест: - на +
ldi r0, -12
ldi r1, 5
smul r0, r1
# Ожидается: r0=-60(0xffc4), r1=-1 (0xFFFF), Flags: N=1

ldi r5, 0x15 # SMUL Тест: 0 на что-то
ldi r0, 0
ldi r1, 99
smul r0, r1
# Ожидается: r0=0, r1=0, Flags: Z=1

# ==========================================
# 2. SDIV (Знаковое деление)
# ==========================================
ldi r5, 0x21 # SDIV Тест: + на +
ldi r0, 17
ldi r1, 5
sdiv r0, r1
# Ожидается: r0=3 (частное), r1=2 (остаток), Flags: Z=0, N=0

ldi r5, 0x22 # SDIV Тест: - на -
ldi r0, -17
ldi r1, -5
sdiv r0, r1
# Ожидается: r0=3, r1=2, Flags: N=0

ldi r5, 0x23 # SDIV Тест: + на -
ldi r0, 17
ldi r1, -5
sdiv r0, r1
# Ожидается: r0=-3, r1=2, Flags: N=1

ldi r5, 0x24 # SDIV Тест: - на +
ldi r0, -17
ldi r1, 5
sdiv r0, r1
# Ожидается: r0=-3, r1=2, Flags: N=1

ldi r5, 0x25 # SDIV Тест: что-то на 0 (Исключение)
ldi r0, 42
ldi r1, 0
sdiv r0, r1
# Ожидается: Генерация исключения деления на ноль (DZ flag/trap)

# ==========================================
# 3. UMUL (Беззнаковое умножение)
# ==========================================
ldi r5, 0x31 # UMUL Тест: + на +
ldi r0, 100
ldi r1, 200
umul r0, r1
# Ожидается: r0=20000(0x4e20), r1=0

ldi r5, 0x32 # UMUL Тест: 0 на что-то
ldi r0, 0
ldi r1, 12345
umul r0, r1
# Ожидается: r0=0, r1=0, Flags: Z=1

ldi r5, 0x33 # UMUL Тест: что-то на 0
ldi r0, 54321
ldi r1, 0
umul r0, r1
# Ожидается: r0=0, r1=0, Flags: Z=1

ldi r5, 0x34 # UMUL Тест: umax на umax
ldi r0, 0xFFFF
ldi r1, 0xFFFF
umul r0, r1
# Ожидается: r0=0x0001, r1=0xFFFE (65535^2 = 0xFFFE0001)

ldi r5, 0x35 # UMUL Тест: 1 на что-то
ldi r0, 1
ldi r1, 8765
umul r0, r1
# Ожидается: r0=8765(0x223d), r1=0

# ==========================================
# 4. UDIV (Беззнаковое деление)
# ==========================================
ldi r5, 0x41 # UDIV Тест: + на +
ldi r0, 100
ldi r1, 7
udiv r0, r1
# Ожидается: r0=14(0xe), r1=2, Flags: Z=0

ldi r5, 0x42 # UDIV Тест: 0 на что-то
ldi r0, 0
ldi r1, 13
udiv r0, r1
# Ожидается: r0=0, r1=0, Flags: Z=1

ldi r5, 0x43 # UDIV Тест: что-то на 1
ldi r0, 9999
ldi r1, 1
udiv r0, r1
# Ожидается: r0=9999(0x270f), r1=0

ldi r5, 0x44 # UDIV Тест: что-то на 0 (Исключение)
ldi r0, 500
ldi r1, 0
udiv r0, r1
# Ожидается: Генерация исключения деления на ноль

ldi r5, 0x45 # UDIV Тест: umax на umax
ldi r0, 0xFFFF
ldi r1, 0xFFFF
udiv r0, r1
# Ожидается: r0=1, r1=0


ldi r5, 0xFF # Маркер успешного окончания
halt
end

# Фоллбэк-цикл (не должен вызываться при корректной работе)
ending:
ldi r3,3
br ending
